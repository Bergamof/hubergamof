/** Élément SVG des dessins, dessiné par le composant (jamais injecté comme texte). */
export interface SvgNode {
	tag: string;
	attrs: Record<string, string>;
	children: SvgNode[];
}

/** Zone cliquable d'un contrôle sur un schéma. */
export interface HitShape {
	id: MouseControlId;
	/** Élément SVG (`rect`, `path`…). */
	tag: string;
	attrs: Record<string, string>;
	/** Identifiant du `clipPath` du schéma qui borne cette zone. */
	clip?: string;
}

/** Un point de vue sur la souris. */
export interface MouseView {
	id: 'top' | 'side';
	caption: string;
	viewBox: string;
	/** Échelle des repères, pour qu'ils gardent la même taille à l'écran quelle que soit la vue. */
	scale: number;
	/** Largeur d'affichage, en pixels. */
	width: number;
	/** Silhouette et détails (balisage SVG de confiance, écrit dans ce fichier). */
	body: SvgNode[];
	hits: HitShape[];
}

/** Où se trouve un contrôle, pour le repère et pour la description. */
export interface ControlSpot {
	id: MouseControlId;
	/** Numéro du repère. */
	number: number;
	/** Nom du contrôle sur ce modèle. */
	label: string;
	/** Où le trouver sur la souris. */
	where: string;
	view: MouseView['id'];
	x: number;
	y: number;
}

export interface MouseArt {
	views: MouseView[];
	spots: ControlSpot[];
}

