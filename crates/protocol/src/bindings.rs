//! Generation of `index.ts`, re-exporting every TypeScript binding.
//!
//! ts-rs writes one file per type but no barrel file. This test (named so that
//! the `export_bindings` filter picks it up) walks the dependency graph of the
//! top-level messages and writes the barrel next to the bindings.

use std::any::TypeId;
use std::collections::{BTreeSet, HashSet};
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

use ts_rs::{Config, TS, TypeVisitor};

use crate::{ApiError, ClientMessage, FileChosen, ImageUploaded, ServerMessage};

const INDEX_FILE: &str = "index.ts";
const HEADER: &str = "// This file was generated by `cargo test -p hubergamof-protocol export_bindings`. Do not edit this file manually.\n";

#[derive(Default)]
struct OutputPaths {
    visited: HashSet<TypeId>,
    paths: BTreeSet<PathBuf>,
}

impl OutputPaths {
    fn collect<T: TS + 'static + ?Sized>(&mut self) {
        if !self.visited.insert(TypeId::of::<T>()) {
            return;
        }
        if let Some(path) = T::output_path() {
            self.paths.insert(path);
        }
        T::visit_dependencies(self);
    }
}

impl TypeVisitor for OutputPaths {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        self.collect::<T>();
    }
}

fn module_specifier(path: &std::path::Path) -> String {
    let without_extension = path.with_extension("");
    format!(
        "./{}",
        without_extension.to_string_lossy().replace('\\', "/")
    )
}

#[test]
fn export_bindings_index() {
    let cfg = Config::from_env();
    ClientMessage::export_all(&cfg).unwrap();
    ServerMessage::export_all(&cfg).unwrap();
    FileChosen::export_all(&cfg).unwrap();
    ImageUploaded::export_all(&cfg).unwrap();
    ApiError::export_all(&cfg).unwrap();

    let mut outputs = OutputPaths::default();
    outputs.collect::<ClientMessage>();
    outputs.collect::<ServerMessage>();
    outputs.collect::<FileChosen>();
    outputs.collect::<ImageUploaded>();
    outputs.collect::<ApiError>();

    let mut index = format!("{HEADER}\n");
    for path in &outputs.paths {
        writeln!(index, "export type * from \"{}\";", module_specifier(path)).unwrap();
    }
    fs::write(cfg.out_dir().join(INDEX_FILE), index).unwrap();
}
